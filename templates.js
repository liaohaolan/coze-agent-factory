/** 按 id 查找模板。 */
export function templateOf(id) {
  return templates.find((entry) => entry.id === id);
}

/** 生成最终提交给 Coze 的人设与回复逻辑（含用户追加要求）。 */
export function buildPrompt(template, extraRequirements) {
  const extra = (extraRequirements ?? '').trim();
  return extra.length === 0 ? template.prompt : `${template.prompt}\n# 附加定制要求\n${extra}`;
}

/** 一目了然的模板目录文本。 */
export function renderCatalog() {
  const rows = templates.map((entry, index) => `${String(index + 1).padStart(2, '0')}. [${entry.id}] ${entry.industry}｜${entry.name}｜${entry.description}`);
  return ['Coze 智能体模板库（共 %d 个行业）：'.replace('%d', String(templates.length)), ...rows, '', '使用 coze_get_template 查看模板全文；使用 coze_create_bot 一键创建到 Coze 空间。'].join('\n');
}
